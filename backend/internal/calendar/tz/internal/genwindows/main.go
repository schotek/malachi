// Command genwindows writes the Windows ↔ IANA time zone table of
// package tz from CLDR's windowsZones.xml (docs/calendar.md D4).
//
//	go run ./internal/calendar/tz/internal/genwindows \
//	    -in <path>/windowsZones.xml -out internal/calendar/tz/windows_zones.go
//
// It reads only the file named by -in and fetches nothing.
package main

import (
	"bytes"
	"encoding/xml"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"
)

type mapZone struct {
	Other     string `xml:"other,attr"`
	Territory string `xml:"territory,attr"`
	Type      string `xml:"type,attr"`
}

type supplemental struct {
	MapTimezones struct {
		OtherVersion string    `xml:"otherVersion,attr"`
		TypeVersion  string    `xml:"typeVersion,attr"`
		Zones        []mapZone `xml:"mapZone"`
	} `xml:"windowsZones>mapTimezones"`
}

func main() {
	in := flag.String("in", "", "path of CLDR windowsZones.xml")
	out := flag.String("out", "windows_zones.go", "Go file to write")
	flag.Parse()
	if *in == "" {
		log.Fatal("genwindows: -in is required")
	}
	raw, err := os.ReadFile(*in)
	if err != nil {
		log.Fatalf("genwindows: %v", err)
	}
	if len(raw) > 4<<20 {
		log.Fatal("genwindows: input larger than 4 MiB")
	}
	src, err := generate(raw)
	if err != nil {
		log.Fatalf("genwindows: %v", err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatalf("genwindows: %v", err)
	}
}

func generate(raw []byte) ([]byte, error) {
	var doc supplemental
	dec := xml.NewDecoder(bytes.NewReader(raw))
	dec.Strict = true
	if err := dec.Decode(&doc); err != nil {
		return nil, fmt.Errorf("parse: %w", err)
	}
	zones := doc.MapTimezones.Zones
	if len(zones) == 0 {
		return nil, fmt.Errorf("no mapZone entries")
	}
	toIANA := map[string]string{}
	toWindows := map[string]string{}
	// Territory 001 entries first: they name a Windows zone's IANA zone
	// and win the reverse mapping of their IANA name.
	for pass := 0; pass < 2; pass++ {
		for _, z := range zones {
			if (z.Territory == "001") != (pass == 0) {
				continue
			}
			win := strings.TrimSpace(z.Other)
			names := strings.Fields(z.Type)
			if win == "" || len(names) == 0 || !plain(win) {
				return nil, fmt.Errorf("bad mapZone %q %q", z.Other, z.Type)
			}
			if pass == 0 {
				toIANA[win] = names[0]
			}
			for _, n := range names {
				if !plain(n) {
					return nil, fmt.Errorf("bad zone name %q", n)
				}
				if _, ok := toWindows[n]; !ok {
					toWindows[n] = win
				}
			}
		}
	}
	for _, z := range zones {
		if _, ok := toIANA[strings.TrimSpace(z.Other)]; !ok {
			return nil, fmt.Errorf("windows zone %q has no territory 001 entry", z.Other)
		}
	}

	var b bytes.Buffer
	b.WriteString(`// SPDX-FileCopyrightText: 2026 Vladislav Janeček
// SPDX-FileCopyrightText: 1991-2026 Unicode, Inc.
// SPDX-License-Identifier: AGPL-3.0-only AND Unicode-3.0

// Code generated by genwindows from CLDR common/supplemental/windowsZones.xml; DO NOT EDIT.
//
// Source: Unicode CLDR windowsZones.xml (`)
	fmt.Fprintf(&b, "otherVersion %s, typeVersion %s", doc.MapTimezones.OtherVersion, doc.MapTimezones.TypeVersion)
	b.WriteString(`),
// https://github.com/unicode-org/cldr, distributed under the Unicode
// License v3 (https://www.unicode.org/license.txt). Regenerate with
// go run ./internal/calendar/tz/internal/genwindows -in windowsZones.xml -out internal/calendar/tz/windows_zones.go

package tz

// windowsToIANA maps a Windows time zone name to the IANA zone of its
// territory 001 entry.
var windowsToIANA = map[string]string{
`)
	writeMap(&b, toIANA)
	b.WriteString("}\n\n// ianaToWindows maps every IANA zone named by any territory entry to its\n// Windows time zone name (territory 001 first).\nvar ianaToWindows = map[string]string{\n")
	writeMap(&b, toWindows)
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func writeMap(b *bytes.Buffer, m map[string]string) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(b, "\t%q: %q,\n", k, m[k])
	}
}

// plain accepts the characters zone names use, so nothing odd lands in
// the generated source.
func plain(s string) bool {
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
		case strings.ContainsRune(" _-+/().,'", r):
		default:
			return false
		}
	}
	return len(s) <= 128
}
